#pragma once
// Lasso tool (Creative, docs/lasso.md). Draw a freehand loop or a circle on the ground; what is inside is selected:
//   Objects    - multi-select placements, then move / rotate about the centre / delete / duplicate them as a group
//   Elevation  - raise or lower the region with a smooth falloff ring outside it; lowered hollows can fill with water
//   Paint      - repaint the region with a ground type (ground_paint.h)
//   Move land  - slide the region's ground shape (and what stands on it) to a new spot
// Every action is one undo step. The region itself is editor state (never saved, never in the map hash); what the
// actions produce (instances, sculpt, water bodies, paint) is saved in the map.
#include "app.h"
#include "lasso_water.h"
#include <functional>

enum LassoMode : int { LM_OBJECTS = 0, LM_ELEVATION, LM_PAINT, LM_MOVELAND, LM_LINE, LM_COUNT };   // LM_LINE: LN1 line features (lasso_line.cpp)
const char* lassoModeName(int m);

struct LassoShape { std::vector<vec2> poly; bool subtract = false; };
// union of the add shapes minus the subtract shapes, in world xz
struct LassoRegion {
  std::vector<LassoShape> shapes;
  bool empty() const;
  bool contains(vec2 p) const;
  float signedDist(vec2 p) const;           // + inside, - outside (union / difference of the shapes' signed distances)
  bool bounds(vec2& lo, vec2& hi) const;    // of the add shapes; false when empty
  void clear() { shapes.clear(); }
  void add(std::vector<vec2> poly, bool subtract = false);   // replaces nothing; drops degenerate loops
  LassoRegion moved(vec2 delta, float yawDeg, vec2 pivot) const;
};

struct LassoParams {
  int mode = LM_OBJECTS;
  bool circle = false;      // shape: freehand loop / circle (press = centre, drag = radius)
  bool touching = false;    // objects: any footprint corner inside (default: the pivot inside)
  // elevation
  float amount = 4.0f;      // metres (+ raise, - lower)
  float falloff = 8.0f;     // metres of blend ring outside the region
  int profile = 0;          // 0 plateau (flat top / floor), 1 dome (rounded hill / bowl)
  bool linearEdge = false;  // falloff curve: smooth (smoothstep) or linear
  bool fillWater = false;   // lowering: fill the hollow with water up to its lip
  // paint
  int paintType = 2;        // ground_paint.h type id
  float paintStrength = 1.0f, paintFeather = 1.5f;
  // move land
  float moveFalloff = 6.0f;
  int groupPolicy = 0;      // LassoGroupPolicy: blocked members on release
};
LassoParams& lassoParams();
LassoRegion& lassoRegion();

// ---------------------------------------------------------------- objects
// select the placements in `r`: op 0 replaces, 1 adds, 2 removes. Furniture generated by a furnished building
// (extra.furnish) is never selected: it follows its host. Returns the selection size.
int lassoSelectObjects(App& app, const LassoRegion& r, int op = 0, bool touching = false);
bool lassoInstanceIn(const App& app, const Instance& i, const LassoRegion& r, bool touching);
vec3 lassoGroupCentre(const App& app);     // mean of the members' pivots
void lassoSanitize(App& app);              // drops ids that no longer exist; keeps `selected` the primary
// a group transform: begin (one undo step), any number of set() calls (offset from the original layout and a turn
// about the original centre), end(commit). A move where any member is invalid is rejected and reverted on end.
// Members never block each other (overlap, crushing, terrain cuts: App::placeIgnore, Terrain::cutIgnore). When some
// members cannot stand at their new spot, `policy` decides on release (always one undo step):
enum LassoGroupPolicy : int { LG_MOVE_REST = 0, LG_CANCEL, LG_PLACE_ANYWAY };
bool lassoGroupBegin(App& app);
bool lassoGroupSet(App& app, vec2 delta, float yawDeg);   // true when every member is placeable
bool lassoGroupEnd(App& app, bool commit, int policy = LG_MOVE_REST);   // true = something moved (kept)
bool lassoGroupActive();
const std::string& lassoGroupReason();
int lassoGroupBlocked();                                   // members blocked at the last set() / end()
bool lassoGroupIsBlocked(uint64_t id);
bool lassoGroupMove(App& app, vec2 delta, float yawDeg, int policy = LG_MOVE_REST);  // begin + set + end
int lassoDeleteGroup(App& app);
int lassoDuplicateGroup(App& app);   // the copies become the selection

