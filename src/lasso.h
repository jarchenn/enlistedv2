float lassoElevWeight(const ElevParams& p, float signedDist, float maxInside);   // 0..1
// a live edit: begin (one undo step) on a region, preview with changing params, apply or cancel
bool lassoElevBegin(App& app, const LassoRegion& r);
void lassoElevPreview(App& app, const ElevParams& p);
bool lassoElevApply(App& app, bool fillWater, WaterFill* fill = nullptr);   // commits sculpt (+ the water body)
void lassoElevCancel(App& app);
bool lassoElevActive();
bool lassoElevate(App& app, const LassoRegion& r, const ElevParams& p, bool fillWater = false, WaterFill* fill = nullptr);   // all in one

