// ---------------------------------------------------------------- builder
class F {
  constructor(id, seed) { this.A = new Asset({}); this.groups = []; this.g = 0; this.used = new Set(); this.cols = []; this.rand = rng(seed); }
  grp(n) { let i = this.groups.indexOf(n); if (i < 0) { this.groups.push(n); i = this.groups.length - 1; } this.g = i; return this; }
  use(m) {
    if (!this.used.has(m)) { const d = PAL[m]; if (!d) throw new Error("unknown material " + m); this.used.add(m); this.A.mat(m, d[0], d[1], d[2], d[3] || {}); }
    return m;
  }
  tag(p) { if (!p) return p; if (!this.groups.length) this.grp("body"); p.k = 0; p.g = this.g; if (Math.max(...p.s) < 0.07) p.lod = 1; return p; }
  b(mn, mx, m, bv) {   // bevelled box, bevel auto from the thinnest side
    const t = Math.min(...[0, 1, 2].map((i) => Math.abs(mx[i] - mn[i])));
    return this.tag(this.A.box(mn, mx, this.use(m), { k: 0, bv: bv ?? Math.min(0.012, Math.max(0.002, t * 0.22)) }));
  }
  ob(c, s, r, m, bv) { return this.tag(this.A.obox(c, s, r, this.use(m), { k: 0, bv: bv ?? Math.min(0.012, Math.max(0.002, Math.min(...s) * 0.22)) })); }
  cy(c, s, m, o = {}) { return this.tag(this.A.cyl(c, s, this.use(m), { k: 0, ...o })); }
  cone(c, s, m, o = {}) { return this.tag(this.A.cone(c, s, this.use(m), { k: 0, ...o })); }
  rb(mn, mx, rad, m) { return this.tag(this.A.rbox(mn, mx, rad, this.use(m), { k: 0 })); }
  wd(c, s, m, o = {}) { return this.tag(this.A.wedge(c, s, this.use(m), { k: 0, ...o })); }
  col(mn, mx) { this.cols.push([mn, mx]); }
  // PR4 soft parts (src/assets.cpp appendSoft): "s" puff (pillows, mattresses, cushions) and "d" drape (duvets, throws,
  // curtains); the mesh fills the box exactly. o: puff, dent, sag, tuft + tx / tz, pipe, wr (wrinkle m), fold (m),
  // rad; drape: drop, th, sides (1 -x, 2 +x, 4 -z, 8 +z), r (euler)
  soft(t, mn, mx, m, o = {}) { return this.softAt(t, [0, 1, 2].map((i) => (mn[i] + mx[i]) / 2), [0, 1, 2].map((i) => Math.abs(mx[i] - mn[i])), m, o); }
  softAt(t, c, s, m, o = {}) {   // c: centre, s: size in the part's own frame (before o.r)
    const p = { t, c: c.map(r3), s: s.map(r3), m: this.use(m), k: 0 };
    for (const [k, v] of Object.entries(o)) if (k !== "r") p[k] = typeof v === "number" ? r3(v) : v;
    if (o.r) p.r = o.r;
    if (p.seed === undefined) p.seed = Math.floor(this.rand() * 1e6);
    this.A._target.push(p); return this.tag(p);
  }
  puff(mn, mx, m, o = {}) { return this.soft("s", mn, mx, m, o); }
  drape(mn, mx, m, o = {}) { return this.soft("d", mn, mx, m, o); }
  pick(list) { return list[Math.floor(this.rand() * list.length) % list.length]; }
}

// rotated-part extent (euler degrees, X then Y then Z; single-axis turns are exact)
function partBox(p) {
  const h = p.s.map((x) => x / 2);
  if (!p.r || p.r.every((a) => !a)) return [p.c.map((c, i) => c - h[i]), p.c.map((c, i) => c + h[i])];
  const [ax, ay, az] = p.r.map((a) => (a * Math.PI) / 180);
  const rot = (v) => {
    let [x, y, z] = v;
    [y, z] = [y * Math.cos(ax) - z * Math.sin(ax), y * Math.sin(ax) + z * Math.cos(ax)];
    [x, z] = [x * Math.cos(ay) + z * Math.sin(ay), -x * Math.sin(ay) + z * Math.cos(ay)];
    [x, y] = [x * Math.cos(az) - y * Math.sin(az), x * Math.sin(az) + y * Math.cos(az)];
    return [x, y, z];
  };
  const mn = [1e9, 1e9, 1e9], mx = [-1e9, -1e9, -1e9];
  for (const sx of [-1, 1]) for (const sy of [-1, 1]) for (const sz of [-1, 1]) {
    const v = rot([sx * h[0], sy * h[1], sz * h[2]]);
    for (let i = 0; i < 3; i++) { mn[i] = Math.min(mn[i], p.c[i] + v[i]); mx[i] = Math.max(mx[i], p.c[i] + v[i]); }
  }
  return [mn, mx];
}

