    const n0 = f.A.parts.length;
    const Z0 = z0, Z1 = z1;   // built facing +z, then mirrored for the -z side
    f.grp("frame");
    f.b([x0, y - 0.025, Z0], [x1, y, Z1], m, 0.003);                                        // shelf deck
